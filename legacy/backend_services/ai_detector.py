from __future__ import annotations

"""ContextTrace AI-media detection engine.

The detector is intentionally evidence-first:
- a video/face detector is the primary learned signal;
- a frame-level detector is a secondary signal;
- deterministic forensic features are supporting evidence;
- temporal aggregation prevents one anomalous frame from dominating;
- calibration is only applied when a calibration artifact produced from a
  representative, held-out calibration set is present.

Without calibration, `aiScore` is an AI-artifact index (0..100), not a
probability and not the percentage of frames generated by AI.
"""

import math
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import cv2
import numpy as np

from .calibration import apply_calibration, load_calibration
from .face import track_largest_faces
from .model_registry import active_profile, configuration_string, load_registry, model_metadata
from .provenance import inspect_c2pa

SAMPLE_FPS = float(os.getenv("CTXTRACE_AI_SAMPLE_FPS", "1.0"))
MAX_FRAMES = int(os.getenv("CTXTRACE_AI_MAX_FRAMES", "96"))
BATCH_SIZE = int(os.getenv("CTXTRACE_AI_BATCH_SIZE", "4"))
PRIMARY_ID = os.getenv("CTXTRACE_PRIMARY_MODEL", "Ant-One/GenD_DINOv3_L_FF")
SECONDARY_ID = os.getenv("CTXTRACE_SECONDARY_MODEL", "dima806/deepfake_vs_real_image_detection")

_models: dict[str, Any] = {}
_processors: dict[str, Any] = {}
_torches: dict[str, Any] = {}
_errors: dict[str, str] = {}


@dataclass
class DetectorFrame:
    timestamp: float
    primary: float | None
    secondary: float | None
    score: float
    face_found: bool
    face_method: str
    face_confidence: float
    forensic: dict[str, float]


def _lazy_model(model_id: str):
    if model_id in _models:
        return _processors.get(model_id), _models[model_id], _torches[model_id]
    if model_id in _errors:
        raise RuntimeError(_errors[model_id])
    try:
        import torch
        from transformers import AutoImageProcessor, AutoModel, AutoModelForImageClassification

        device = "cuda" if torch.cuda.is_available() else "cpu"
        if "GenD_" in model_id or "video-deepfake" in model_id:
            model = AutoModel.from_pretrained(model_id, trust_remote_code=True)
            processor = None
        else:
            processor = AutoImageProcessor.from_pretrained(model_id)
            model = AutoModelForImageClassification.from_pretrained(model_id)
        model = model.to(device)
        model.eval()
        _models[model_id] = model
        _processors[model_id] = processor
        _torches[model_id] = torch
        return processor, model, torch
    except Exception as exc:  # pragma: no cover - model/runtime dependent
        message = f"Model unavailable ({model_id}): {type(exc).__name__}: {exc}"
        _errors[model_id] = message
        raise RuntimeError(message) from exc


def _sample_frames(path: Path, duration: float) -> list[tuple[float, np.ndarray]]:
    cap = cv2.VideoCapture(str(path))
    if not cap.isOpened():
        raise RuntimeError("Could not open video for AI analysis.")
    count = min(MAX_FRAMES, max(12, int(math.ceil(max(duration, 1.0) * max(0.25, SAMPLE_FPS)))))
    times = np.linspace(0.0, max(0.0, duration - 0.05), count)
    out: list[tuple[float, np.ndarray]] = []
    try:
        for timestamp in times:
            cap.set(cv2.CAP_PROP_POS_MSEC, float(timestamp) * 1000.0)
            ok, frame = cap.read()
            if ok and frame is not None:
                out.append((float(timestamp), frame))
    finally:
        cap.release()
    if len(out) < 6:
        raise RuntimeError(f"Only {len(out)} decodable frames were available for AI analysis.")
    return out


def _forensic(frame: np.ndarray, prev_gray: np.ndarray | None) -> tuple[dict[str, float], np.ndarray]:
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY).astype(np.float32)
    hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)
    saturation = float(np.mean(hsv[:, :, 1]) / 255.0)
    lap = cv2.Laplacian(gray, cv2.CV_32F)
    high_frequency = float(np.mean(np.abs(lap)))
    hist = cv2.calcHist([gray.astype(np.uint8)], [0], None, [64], [0, 256]).ravel().astype(np.float64)
    hist /= max(float(hist.sum()), 1.0)
    entropy = float(-(hist[hist > 0] * np.log2(hist[hist > 0])).sum())
    sharpness = float(lap.var())
    block = 0.0
    if gray.shape[0] > 16 and gray.shape[1] > 16:
        v = np.abs(np.diff(gray, axis=1)); h = np.abs(np.diff(gray, axis=0))
        seam = (v[:, 7::8].mean() if v[:, 7::8].size else 0.0) + (h[7::8, :].mean() if h[7::8, :].size else 0.0)
        off = (v[:, 3::8].mean() if v[:, 3::8].size else 0.0) + (h[3::8, :].mean() if h[3::8, :].size else 0.0)
        block = float(seam / max(off, 1e-6))
    flicker = 0.0 if prev_gray is None else float(np.mean(np.abs(gray - prev_gray)) / max(np.mean(gray), 1.0))
    return {
        "saturation": saturation,
        "high_frequency": high_frequency,
        "entropy": entropy,
        "sharpness": sharpness,
        "blockiness": block,
        "temporal_flicker": flicker,
    }, gray


def _fake_index(model_id: str, model: Any) -> int:
    if "GenD_" in model_id or "video-deepfake" in model_id:
        return 1
    mapping = getattr(getattr(model, "config", None), "id2label", {}) or {}
    for idx, label in mapping.items():
        if any(term in str(label).lower() for term in ("fake", "synthetic", "deepfake", "manipulated")):
            return int(idx)
    return 1


def _predict(model_id: str, images: list[Any]) -> list[float]:
    processor, model, torch = _lazy_model(model_id)
    device = next(model.parameters()).device
    fake_idx = _fake_index(model_id, model)
    output: list[float] = []
    for start in range(0, len(images), BATCH_SIZE):
        batch = images[start:start + BATCH_SIZE]
        if processor is None and hasattr(model, "feature_extractor"):
            tensors = []
            for image in batch:
                tensor = model.feature_extractor.preprocess(image)
                if getattr(tensor, "ndim", 0) == 4:
                    tensor = tensor.squeeze(0)
                tensors.append(tensor)
            inputs = torch.stack(tensors).to(device)
            with torch.inference_mode():
                logits = model(inputs)
                logits = logits.logits if hasattr(logits, "logits") else logits
        else:
            inputs = processor(images=batch, return_tensors="pt")
            inputs = {key: value.to(device) for key, value in inputs.items()}
            with torch.inference_mode():
                logits = model(**inputs).logits
        probs = torch.softmax(logits, dim=-1)[:, fake_idx].detach().cpu().numpy().tolist()
        output.extend(float(np.clip(x, 0.0, 1.0)) for x in probs)
    return output


def _aggregate(values: list[float]) -> float:
    if not values:
        return 0.5
    a = np.clip(np.asarray(values, dtype=np.float64), 0.0, 1.0)
    # Median is deliberately dominant: a small number of anomalous frames must
    # not make the entire video "AI".
    return float(np.clip(0.55 * np.median(a) + 0.30 * np.percentile(a, 75) + 0.15 * np.mean(np.sort(a)[-max(1, int(math.ceil(len(a) * .10))):]), 0, 1))


def _forensic_support(rows: list[dict[str, float]]) -> float:
    if not rows:
        return 0.5
    mean = {key: float(np.mean([row[key] for row in rows])) for key in rows[0]}
    # Supporting-only index. These are not universal AI signatures.
    signals = [
        float(np.clip((mean["blockiness"] - 1.0) / 0.8, 0, 1)),
        float(np.clip((mean["temporal_flicker"] - 0.02) / 0.12, 0, 1)),
        float(1.0 - np.clip((mean["entropy"] - 2.0) / 4.0, 0, 1)),
    ]
    return float(np.mean(signals))


def analyze_video(path: Path, duration: float) -> dict[str, Any]:
    frames = _sample_frames(path, duration)
    cap = cv2.VideoCapture(str(path))
    width, height = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH) or 0), int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT) or 0)
    fps = float(cap.get(cv2.CAP_PROP_FPS) or 0)
    cap.release()

    from PIL import Image

    profile = active_profile()
    registry = load_registry().get("models", {})
    primary_id = os.getenv("CTXTRACE_PRIMARY_MODEL") or (registry.get(profile.get("primary", ""), {}).get("source") if profile.get("primary") else "")
    secondary_id = os.getenv("CTXTRACE_SECONDARY_MODEL") or (registry.get(profile.get("secondary", ""), {}).get("source") if profile.get("secondary") else "")
    full_images: list[Any] = []
    face_images: list[Any] = []
    frame_face_flags: list[dict[str, Any]] = []
    forensic_rows: list[dict[str, float]] = []
    prev_gray = None

    tracked_faces = track_largest_faces(frames)
    for (timestamp, frame), (face, face_meta) in zip(frames, tracked_faces):
        forensic, gray = _forensic(frame, prev_gray)
        prev_gray = gray
        frame_face_flags.append({"timestamp": timestamp, **face_meta})
        forensic_rows.append(forensic)
        full_images.append(Image.fromarray(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)))
        if face is not None:
            face_images.append(Image.fromarray(cv2.cvtColor(face, cv2.COLOR_BGR2RGB)))

    secondary_scores: list[float] | None = None
    primary_scores: list[float | None] = [None] * len(frames)
    warnings: list[str] = []

    try:
        if secondary_id:
            secondary_scores = _predict(secondary_id, full_images)
    except Exception as exc:
        warnings.append(str(exc))

    try:
        if primary_id and face_images:
            face_scores = _predict(primary_id, face_images)
            fi = 0
            for idx, meta in enumerate(frame_face_flags):
                if meta["found"]:
                    primary_scores[idx] = face_scores[fi]
                    fi += 1
    except Exception as exc:
        warnings.append(str(exc))

    rows: list[DetectorFrame] = []
    for idx, ((timestamp, _frame), meta, forensic) in enumerate(zip(frames, frame_face_flags, forensic_rows)):
        secondary = secondary_scores[idx] if secondary_scores and idx < len(secondary_scores) else None
        primary = primary_scores[idx]
        if primary is not None and secondary is not None:
            score = 0.70 * primary + 0.30 * secondary
        elif primary is not None:
            score = primary
        elif secondary is not None:
            score = secondary
        else:
            score = 0.5
        rows.append(DetectorFrame(timestamp, primary, secondary, float(score), bool(meta["found"]), str(meta["method"]), float(meta["confidence"]), forensic))

    frame_scores = [row.score for row in rows]
    learned = _aggregate(frame_scores)
    agreement = float(np.clip(1.0 - np.std(frame_scores) * 2.2, 0.0, 1.0))
    face_coverage = float(np.mean([row.face_found for row in rows]))
    forensic = _forensic_support(forensic_rows)

    # Forensic evidence has no learned calibration, therefore it remains a
    # supporting term rather than pretending to be an independent probability.
    raw_index = float(np.clip(0.88 * learned + 0.12 * forensic, 0.0, 1.0))
    calibration = load_calibration()
    calibrated = apply_calibration(raw_index, calibration)
    score = calibrated if calibrated is not None else raw_index
    score_type = "calibrated_probability" if calibrated is not None else "uncalibrated_ai_artifact_index"
    confidence = float(np.clip(0.35 + 0.35 * agreement + 0.20 * min(1.0, len(rows) / 48) + 0.10 * (1.0 if secondary_scores else 0.0), 0.20, 0.97))
    if not secondary_scores and not any(x is not None for x in primary_scores):
        raise RuntimeError("No learned detector was available. Refusing to emit an AI score without learned evidence.")

    high = [row for row in rows if row.score >= 0.70]
    findings = [
        {
            "componentId": "learned_detector",
            "label": "Learned detector",
            "severity": "high" if learned >= 0.75 else "medium" if learned >= 0.50 else "low",
            "score": round(learned, 4),
            "timestamp": max(rows, key=lambda r: r.score).timestamp,
            "frameValue": max(r.score for r in rows),
            "breachPct": round(100 * len(high) / len(rows), 1),
            "explanation": "Learned frame-level predictions aggregated across the video; isolated spikes are down-weighted.",
        }
    ] if rows else []
    if face_coverage > 0:
        findings.append({
            "componentId": "face_temporal_detector",
            "label": "Face-video detector",
            "severity": "high" if any(r.primary is not None and r.primary >= .75 for r in rows) else "medium",
            "score": round(_aggregate([r.primary for r in rows if r.primary is not None]), 4) if any(r.primary is not None for r in rows) else 0.5,
            "timestamp": next((r.timestamp for r in rows if r.primary is not None and r.primary >= .75), rows[0].timestamp),
            "frameValue": max([r.primary or 0 for r in rows], default=0),
            "breachPct": round(100 * sum(1 for r in rows if r.primary is not None and r.primary >= .70) / max(1, sum(1 for r in rows if r.primary is not None)), 1),
            "explanation": f"Face detector coverage was {face_coverage:.1%}; face-level evidence is included where available.",
        })

    learned_conf = float(np.clip(0.40 + 0.60 * agreement, 0.0, 1.0))
    components = [
        {"id": "learned_detector", "label": "Learned detector", "score": round(learned, 4), "confidence": round(learned_conf, 4), "summary": "Primary learned detector aggregate across sampled frames."},
        {"id": "face_temporal_detector", "label": "Face-video detector", "score": round(_aggregate([r.primary for r in rows if r.primary is not None]), 4) if any(r.primary is not None for r in rows) else 0.5, "confidence": round(face_coverage, 4), "summary": f"Face-level detector coverage: {face_coverage:.1%}."},
        {"id": "frame_detector", "label": "Frame detector", "score": round(_aggregate([r.secondary for r in rows if r.secondary is not None]), 4) if any(r.secondary is not None for r in rows) else 0.5, "confidence": round(1.0 if secondary_scores else 0.0, 4), "summary": "Secondary image-level detector applied frame-wise."},
        {"id": "temporal_consistency", "label": "Temporal consistency", "score": round(agreement, 4), "confidence": round(agreement, 4), "summary": "Agreement of learned predictions across time; low agreement reduces confidence."},
        {"id": "forensic_support", "label": "Forensic support", "score": round(forensic, 4), "confidence": 0.35, "summary": "Compression and temporal forensic measurements used only as supporting evidence."},
    ]

    provenance = inspect_c2pa(path)

    return {
        "aiScore": int(round(score * 100)),
        "rawAiArtifactIndex": round(raw_index * 100, 2),
        "calibratedProbability": round(calibrated * 100, 2) if calibrated is not None else None,
        "scoreType": score_type,
        "confidence": round(confidence, 4),
        "components": components,
        "modelTrainingNote": "Research ensemble. Reported third-party model metrics are retained as provenance only; project-level accuracy is not claimed until the supplied generator-disjoint evaluation protocol is run.",
        "learnedDetectorScore": round(learned * 100, 2),
        "forensicSupportScore": round(forensic * 100, 2),
        "temporalAgreement": round(agreement, 4),
        "faceCoverage": round(face_coverage, 4),
        "analyzedFrames": len(rows),
        "sampledAt": [r.timestamp for r in rows],
        "findings": findings,
        "frameScores": [
            {"timestamp": r.timestamp, "score": round(r.score * 100, 2), "primaryScore": None if r.primary is None else round(r.primary * 100, 2), "secondaryScore": None if r.secondary is None else round(r.secondary * 100, 2), "faceDetected": r.face_found, "faceMethod": r.face_method}
            for r in rows
        ],
        "forensic": {key: round(float(np.mean([r.forensic[key] for r in rows])), 6) for key in rows[0].forensic},
        "durationSeconds": duration,
        "meta": {"width": width, "height": height, "fpsEstimate": fps, "hasAudio": True},
        "modelVersion": configuration_string(),
        "modelRegistry": {"primary": model_metadata(profile.get("primary", "gend_dinov3_ff")), "secondary": model_metadata(profile.get("secondary", "frame_vit_deepfake")), "calibration": calibration or {"status": "not_installed"}},
        "warnings": warnings,
        "provenance": provenance,
        "limitations": [
            "AI-artifact detection is probabilistic and can fail on unseen generators, codecs, resolutions and post-processing pipelines.",
            "The score is not a percentage of pixels, frames, or authorship attributable to AI.",
            "A calibrated probability is shown only after a project-specific held-out calibration artifact is installed.",
            "Face-level evidence only applies to frames where a face was detected.",
            "Forensic features are supporting evidence and are not independently validated as universal AI signatures.",
        ],
    }


def run_ai_scan(job_id: str) -> None:
    from datetime import datetime, timezone
    from sqlalchemy import select
    from ..db import SessionLocal
    from ..models import AnalysisJob, Report, Video
    from .forensics import extract_ocr

    db = SessionLocal()
    try:
        job = db.get(AnalysisJob, job_id)
        if not job:
            return
        video = db.get(Video, job.source_video_id) if job.source_video_id else None
        if not video:
            raise RuntimeError("Scan video was not found.")
        job.status = "RUNNING"; job.current_stage = "learned_detector"; job.progress = 15; job.started_at = job.started_at or datetime.now(timezone.utc); db.commit()
        result = analyze_video(Path(video.storage_path), video.duration_seconds)
        job.current_stage = "ocr_evidence"; job.progress = 82; db.commit()
        ocr, ocr_warning = extract_ocr(Path(video.storage_path), video.duration_seconds)
        result["ocrObservations"] = ocr
        result["ocrCoverage"] = 0.0 if ocr_warning else (1.0 if ocr else 0.5)
        warnings = list(result.get("warnings", []))
        degraded = False
        if ocr_warning:
            warnings.append(ocr_warning); degraded = True
        result["warnings"] = warnings
        report = db.scalar(select(Report).where(Report.job_id == job.id))
        payload = {
            "scanResult": result,
            "interpretation": "Single-video AI-artifact screening. The score is a calibrated probability only when a project-specific calibration artifact is installed; otherwise it is an uncalibrated AI-artifact index. It is not proof of origin or authorship.",
        }
        if report is None:
            report = Report(job_id=job.id, owner_id=job.owner_id, score=int(result["aiScore"]), overall_confidence=float(result["confidence"]), evidence_coverage=float(result.get("ocrCoverage", 0.0)), uncertainty=max(0.0, 1.0 - float(result["confidence"])), interpretation=payload["interpretation"], pipeline_version="ctxtrace-ai-scan v3.0", model_configuration=result["modelVersion"], degraded=degraded, event_count=len(result.get("findings", [])), report_json=payload)
            db.add(report)
        else:
            report.score = int(result["aiScore"]); report.overall_confidence = float(result["confidence"]); report.evidence_coverage = float(result.get("ocrCoverage", 0.0)); report.uncertainty = max(0.0, 1.0 - float(result["confidence"])); report.degraded = degraded; report.report_json = payload
        job.status = "DEGRADED" if degraded else "COMPLETED"; job.current_stage = "report_generation"; job.progress = 100; job.warnings = warnings; job.completed_at = datetime.now(timezone.utc); job.model_configuration = result["modelVersion"]; db.commit()
    except Exception as exc:
        db.rollback()
        job = db.get(AnalysisJob, job_id)
        if job:
            job.status = "FAILED"; job.current_stage = "failed"; job.error_message = f"AI analysis failed: {type(exc).__name__}: {exc}"; job.completed_at = datetime.now(timezone.utc); db.commit()
    finally:
        db.close()
